0 VALUE GENERATION

: SWAP-BOARDS OLD-BOARD NEW-BOARD TO OLD-BOARD TO NEW-BOARD ;

: UPDATE-BOARD
  TOTAL-ROWS 2 - 1 DO
    TOTAl-ROW-SIZE 2 - 1 DO
      OLD-BOARD J TOTAL-ROW-SIZE * + I +
      DUP 1- C@
      OVER 1+ C@ +
      OVER TOTAL-ROW-SIZE - 1- C@ +
      OVER TOTAL-ROW-SIZE - C@ + 
      OVER TOTAL-ROW-SIZE - 1+ C@ +
      OVER TOTAL-ROW-SIZE + 1- C@ +
      OVER TOTAL-ROW-SIZE +  C@ +
      OVER TOTAL-ROW-SIZE + 1+ C@ +
      DUP 2 < IF
        2DROP 0
      ELSE
        DUP 2 = IF
	  DROP C@
	ELSE
	  3 = IF
	    DROP 1
	  ELSE
	    DROP 0
	  THEN
	THEN
      THEN
      NEW-BOARD J TOTAL-ROW-SIZE * + I + C!
    LOOP
  LOOP ;


