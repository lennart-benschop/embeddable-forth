  CLG
  BOARD-HEIGHT 0 DO
    BOARD-WIDTH 0 DO
      OLD-BOARD J MARGIN + 1+ TOTAL-ROW-SIZE * + I MARGIN + 1+ + C@
      IF PATTERN I 4 * J 4 * 4 4 PUT-BITMAP-MONO THEN
    LOOP
  LOOP REDRAW ;

