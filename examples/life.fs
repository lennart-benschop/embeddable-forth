: FILL-BOARD
  OLD-BOARD TOTAl-ROW-SIZE TOTAl-ROWS * ERASE
  MARGIN 1+ BOARD-HEIGHT BOUNDS DO
    MARGIN 1+ BOARD-WIDTH BOUNDS DO
     4 RAND 0= IF 1  OLD-BOARD J TOTAL-ROW-SIZE * + I + C! THEN
    LOOP
  LOOP ;

