: DRAW-BOARD
  CLG
  BOARD-HEIGHT 0 DO
    BOARD-WIDTH 0 DO
      OLD-BOARD J MARGIN + 1+ TOTAL-ROW-SIZE * + I MARGIN + 1+ + C@
      IF I J PLOTDOT THEN
    LOOP
  LOOP REDRAW ;

[ELSE]
